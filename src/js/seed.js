export function seed() {
  return RAW.map(([d, h, m, source, pinned, text]) => {
    const t = at(d, h, m);
    return {
      id: crypto.randomUUID(),
      createdAt: t,
      updatedAt: t,
      deletedAt: null,
      rev: 1,
      text,
      pinned,
      source,
      refs: [],
      blobs: [],
      dirty: false,
    };
  });
}
